<script setup lang="ts">
import { ref } from 'vue';
import { Head, useForm } from '@inertiajs/vue3';
import BaseInput from '@/Components/Forms/BaseInput.vue';
import BaseButton from '@/Components/UI/BaseButton.vue';
import { ShieldCheck, KeyRound } from 'lucide-vue-next';

const recovery = ref(false);

const form = useForm({
    code: '',
    recovery_code: '',
});

const toggleRecovery = () => {
    recovery.value = !recovery.value;
    form.clearErrors();
    form.code = '';
    form.recovery_code = '';
};

const submit = () => {
    form.post('/two-factor-challenge', {
        onFinish: () => {
            if (!recovery.value) {
                form.reset('code');
            } else {
                form.reset('recovery_code');
            }
        },
    });
};
</script>

<template>
    <Head title="Two-Factor Authentication - StoreFleet" />

    <div class="min-h-screen flex items-center justify-center" style="padding: var(--space-4); background-color: var(--bg-page);">
        <div class="card card-elevated" style="max-width: 440px; width: 100%; padding: var(--space-8);">
            <!-- Icon & Header -->
            <div style="text-align: center; margin-bottom: var(--space-6);">
                <div style="width: 3.5rem; height: 3.5rem; border-radius: 50%; background-color: var(--primary-light); color: var(--primary); display: inline-flex; align-items: center; justify-content: center; margin-bottom: var(--space-3);">
                    <ShieldCheck :size="28" />
                </div>
                <h1 style="font-size: 1.4rem; font-weight: 700; margin-bottom: var(--space-1); color: var(--text-primary);">Two-Factor Authentication</h1>
                <p style="font-size: 0.875rem; color: var(--text-secondary);">
                    {{ recovery 
                        ? 'Enter one of your emergency recovery codes to authenticate.' 
                        : 'Enter the 6-digit authentication code generated by your authenticator app.' 
                    }}
                </p>
            </div>

            <!-- Form -->
            <form @submit.prevent="submit">
                <template v-if="!recovery">
                    <BaseInput
                        v-model="form.code"
                        label="6-Digit Authentication Code"
                        type="text"
                        placeholder="123456"
                        required
                        :error="form.errors.code"
                        class="mono"
                        style="letter-spacing: 0.25em; font-size: 1.25rem; text-align: center;"
                        autocomplete="one-time-code"
                    />
                </template>

                <template v-else>
                    <BaseInput
                        v-model="form.recovery_code"
                        label="Emergency Recovery Code"
                        type="text"
                        placeholder="XXXX-XXXX-XXXX"
                        required
                        :error="form.errors.recovery_code"
                        class="mono"
                        autocomplete="off"
                    >
                        <template #leading><KeyRound :size="16" /></template>
                    </BaseInput>
                </template>

                <div style="margin-top: var(--space-4); margin-bottom: var(--space-6); text-align: center;">
                    <button
                        type="button"
                        @click="toggleRecovery"
                        class="btn btn-ghost btn-sm"
                        style="color: var(--primary); font-size: 0.825rem;"
                    >
                        {{ recovery ? 'Use an authenticator code instead' : 'Use an emergency recovery code' }}
                    </button>
                </div>

                <BaseButton
                    type="submit"
                    variant="primary"
                    style="width: 100%;"
                    :loading="form.processing"
                >
                    Verify &amp; Continue
                </BaseButton>
            </form>
        </div>
    </div>
</template>
